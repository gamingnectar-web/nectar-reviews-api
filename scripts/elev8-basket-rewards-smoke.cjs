'use strict';
const assert=require('node:assert/strict');
const E=require('../public/elev8-basket-rewards-engine.js');
const items=[{unitPrice:32.99,quantity:2,vendor:'GFUEL',tags:[]}];
let r=E.evaluate(E.defaultRules,items);
assert.equal(r.rows.find(x=>x.id==='reward-50').available,true);
assert.equal(r.rows.find(x=>x.id==='reward-75').available,false);
assert.equal(r.rows.find(x=>x.id==='reward-50').needsChoice,true);
assert.equal(r.estimatedProductSaving,0);
r=E.evaluate(E.defaultRules,items,{'reward-50':'r50-percent'});
assert.equal(r.estimatedProductSaving,3.3);
r=E.evaluate(E.defaultRules,[{unitPrice:100,quantity:1,vendor:'GFUEL',tags:[]}],{'reward-50':'r50-percent'});
assert.equal(r.applied.length,3);
const noStack=E.clone(E.defaultRules);noStack[1].stackWith=[];
r=E.evaluate(noStack,[{unitPrice:100,quantity:1,vendor:'GFUEL',tags:[]}],{'reward-50':'r50-percent'});
assert.ok(r.suppressed.length>=1);
const excluded=E.clone(E.defaultRules);excluded[0].excludeVendors=['GFUEL'];
r=E.evaluate(excluded,items);assert.equal(r.rows.find(x=>x.id==='reward-50').available,false);
assert.deepEqual(E.validate(E.defaultRules),[]);
const invalid=E.clone(E.defaultRules);invalid[0].threshold=-1;
assert.ok(E.validate(invalid).length>0);
console.log('✓ 8 basket rewards draft checks passed (unlock, choice, estimate, stack, exclusion, validation)');
