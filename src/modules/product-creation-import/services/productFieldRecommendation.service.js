const ProductImportBatch = require('../productImportBatch.model');
const { cleanText } = require('../utils/safe');
const { getSnapshot } = require('./merchantCatalogueContext.service');

function keyText(value='') {
  return cleanText(value || '', 400).toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

function titleTokens(value='') {
  return new Set(keyText(value).split(/\s+/).filter((word) =>
    word.length > 2 &&
    !['the','and','for','with','from','product','drink','energy','powder','tub','box','uk','stock'].includes(word)
  ));
}

function overlap(a='', b='') {
  const left = titleTokens(a);
  const right = titleTokens(b);
  let total = 0;
  left.forEach((token) => { if (right.has(token)) total += 1; });
  return total;
}

function similarExamples(draft={}, examples=[]) {
  const vendor = keyText(draft.vendor || '');
  const type = keyText(draft.productType || '');

  return (examples || [])
    .map((product) => {
      let score = 0;
      if (vendor && keyText(product.vendor || '') === vendor) score += 55;
      if (type && keyText(product.productType || '') === type) score += 30;
      score += Math.min(24, overlap(draft.title || '', product.title || '') * 8);

      const family = keyText([draft.title, draft.productType].filter(Boolean).join(' '));
      const hay = keyText([product.title, product.productType].filter(Boolean).join(' '));
      if (/hydration/.test(family) && /hydration/.test(hay)) score += 15;
      if (/collector/.test(family) && /collector/.test(hay)) score += 15;
      if (/shaker|cup/.test(family) && /shaker|cup/.test(hay)) score += 15;
      if (/powder|serving|formula/.test(family) && /powder|serving|formula/.test(hay)) score += 10;

      return { product, score };
    })
    .filter((row) => row.score >= 35)
    .sort((a, b) => b.score - a.score)
    .slice(0, 10);
}

function mode(values=[]) {
  const counts = new Map();
  for (const raw of values) {
    const value = cleanText(raw || '', 220);
    if (!value) continue;
    counts.set(value, (counts.get(value) || 0) + 1);
  }
  return [...counts.entries()].sort((a, b) => b[1] - a[1])[0]?.[0] || '';
}

function stripHtml(value='') {
  return cleanText(
    String(value || '')
      .replace(/<br\s*\/?>/gi, '\n')
      .replace(/<\/p>/gi, '\n\n')
      .replace(/<[^>]+>/g, ' ')
      .replace(/\s+/g, ' '),
    4000
  );
}

function getPath(obj={}, path='') {
  return String(path || '').split('.').reduce((value, part) => value == null ? undefined : value[part], obj);
}

function sameValue(a, b) {
  if (Array.isArray(a) || Array.isArray(b)) {
    return JSON.stringify(a || []) === JSON.stringify(b || []);
  }
  return String(a ?? '').trim() !== '' && String(a ?? '').trim() === String(b ?? '').trim();
}

function metafield(draft={}, compound='') {
  return (draft.metafields || []).find((row) => `${row.namespace}.${row.key}` === compound);
}

function sourceRecord(key, label, detail='') {
  return { key, label, detail };
}

function scalarSource(draft={}, cataloguePresets={}, path='') {
  const lock = draft.fieldLocks?.[path];
  if (lock?.locked) return sourceRecord('product_override', 'Product override', 'A merchant edit is locked for this product.');

  const value = getPath(draft, path);
  if (value === undefined || value === null || String(value).trim() === '') {
    return sourceRecord('empty', 'Empty', 'No value has been selected yet.');
  }

  const catalogueMap = {
    vendor: 'vendor',
    productType: 'productType',
    productCategory: 'productCategory',
    themeTemplate: 'themeTemplate',
    collections: 'collections',
  };
  const presetKey = catalogueMap[path];
  if (presetKey && sameValue(value, cataloguePresets?.[presetKey])) {
    return sourceRecord('catalogue_default', 'Catalogue default', 'Inherited from the supplier catalogue preset.');
  }

  const merchantContext = draft.enrichment?.merchantCatalogue || {};
  if (
    path === 'productType' &&
    merchantContext.similarProductCount > 0 &&
    sameValue(value, merchantContext.learnedProductType)
  ) {
    return sourceRecord('shop_recommendation', 'Shop recommendation', `Learnt from ${merchantContext.similarProductCount} similar Shopify product(s).`);
  }

  if (draft.fieldInference?.[path] === true) {
    return sourceRecord('shop_recommendation', 'Shop recommendation', 'Filled from existing merchant catalogue patterns.');
  }

  const aiFields = draft.aiEnrichment?.fields || draft.enrichment?.aiFields || {};
  if (getPath(aiFields, path)) {
    return sourceRecord('ai_suggestion', 'AI suggestion', 'Generated by ELEV8 AI enrichment.');
  }

  return sourceRecord('supplier', 'Supplier', 'Taken from the supplier/product source or initial extraction.');
}

function metafieldSource(draft={}, compound='') {
  const lock = draft.fieldLocks?.[`metafields.${compound}`];
  if (lock?.locked) return sourceRecord('product_override', 'Product override', 'A merchant edit is locked for this product.');

  const row = metafield(draft, compound);
  if (!row || String(row.value ?? '').trim() === '') return sourceRecord('empty', 'Empty', 'No value has been selected yet.');

  const source = String(row.source || '').toLowerCase();
  if (row.merchantLocked || /merchant|manual|user/.test(source)) return sourceRecord('product_override', 'Product override', 'Set directly for this product.');
  if (/catalogue-preset/.test(source)) return sourceRecord('catalogue_default', 'Catalogue default', 'Inherited from the supplier catalogue preset.');
  if (/shopify-catalogue-pattern|shop-pattern/.test(source)) return sourceRecord('shop_recommendation', 'Shop recommendation', 'Learnt from similar products already in Shopify.');
  if (/ai/.test(source)) return sourceRecord('ai_suggestion', 'AI suggestion', 'Generated by ELEV8 AI enrichment.');
  return sourceRecord('supplier', 'Supplier', 'Taken from supplier data or product extraction.');
}

function buildProvenance(draft={}, cataloguePresets={}) {
  return {
    title: scalarSource(draft, cataloguePresets, 'title'),
    descriptionHtml: scalarSource(draft, cataloguePresets, 'descriptionHtml'),
    price: scalarSource(draft, cataloguePresets, 'price'),
    compareAtPrice: scalarSource(draft, cataloguePresets, 'compareAtPrice'),
    sku: scalarSource(draft, cataloguePresets, 'sku'),
    barcode: scalarSource(draft, cataloguePresets, 'barcode'),
    vendor: scalarSource(draft, cataloguePresets, 'vendor'),
    productType: scalarSource(draft, cataloguePresets, 'productType'),
    productCategory: scalarSource(draft, cataloguePresets, 'productCategory'),
    'seo.title': scalarSource(draft, cataloguePresets, 'seo.title'),
    'seo.description': scalarSource(draft, cataloguePresets, 'seo.description'),
    handle: scalarSource(draft, cataloguePresets, 'handle'),
    flavour: metafieldSource(draft, 'core.product_flavour'),
    formula: metafieldSource(draft, 'core.formula_version'),
  };
}

function seoSuffix(examples=[]) {
  const suffixes = examples
    .map(({ product }) => cleanText(product.seoTitle || '', 220))
    .map((value) => value.match(/(?:\||-|–|—)\s*([^|–—-]{3,80})$/)?.[1]?.trim() || '')
    .filter(Boolean);
  return mode(suffixes);
}

function pushRecommendation(out, row) {
  if (!row?.field || row.value === undefined || row.value === null || String(row.value).trim() === '') return;
  const existing = out.find((item) => item.field === row.field);
  if (!existing) out.push(row);
}

async function aiCopyRecommendations({ draft={}, examples=[] }) {
  if (!process.env.OPENAI_API_KEY || !examples.length) return null;

  const facts = {
    title: cleanText(draft.title || '', 220),
    vendor: cleanText(draft.vendor || '', 120),
    productType: cleanText(draft.productType || '', 120),
    description: stripHtml(draft.descriptionHtml || '').slice(0, 2800),
    flavour: cleanText(metafield(draft, 'core.product_flavour')?.value || '', 120),
    formula: cleanText(metafield(draft, 'core.formula_version')?.value || '', 120),
  };

  const shopExamples = examples.slice(0, 8).map(({ product }) => ({
    title: product.title || '',
    productType: product.productType || '',
    description: stripHtml(product.descriptionHtml || '').slice(0, 1000),
    seoTitle: product.seoTitle || '',
    seoDescription: product.seoDescription || '',
  }));

  const prompt = `Create SHOP-AWARE COPY SUGGESTIONS for one ecommerce product.

CURRENT PRODUCT FACTS (the only factual source you may use):
${JSON.stringify(facts, null, 2)}

SIMILAR EXISTING PRODUCTS FROM THIS MERCHANT (style/format examples only):
${JSON.stringify(shopExamples, null, 2)}

Return JSON only with keys:
title, descriptionHtml, seoTitle, seoDescription

Rules:
- Never invent ingredients, benefits, serving counts, nutrition, licensing, stock status, size, price, flavour or product claims.
- Similar products teach style and structure only; they are NOT factual sources for this product.
- Preserve the current product identity.
- descriptionHtml may use simple <p> tags only.
- Keep SEO title concise and SEO description natural.
- If the current facts are insufficient to safely improve a field, return an empty string for that field.
- Do not use markdown.`;

  try {
    const model = process.env.OPENAI_PRODUCT_IMPORT_MODEL || process.env.OPENAI_MODULE_MODEL || 'gpt-4.1-mini';
    const response = await fetch('https://api.openai.com/v1/chat/completions', {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${process.env.OPENAI_API_KEY}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        model,
        temperature: 0.15,
        response_format: { type: 'json_object' },
        messages: [
          { role: 'system', content: 'You create conservative ecommerce copy suggestions from merchant product facts and merchant style examples. You never invent product facts.' },
          { role: 'user', content: prompt },
        ],
      }),
    });

    const json = await response.json();
    if (!response.ok) throw new Error(json?.error?.message || `OpenAI request failed (${response.status})`);
    return JSON.parse(json?.choices?.[0]?.message?.content || '{}');
  } catch (error) {
    return { error: cleanText(error.message || 'AI suggestion failed.', 500) };
  }
}

async function buildProductFieldRecommendations({ shopDomain, batchId, itemId, useAi=false }) {
  const batch = await ProductImportBatch.findOne({ _id: batchId, shopDomain }).lean();
  if (!batch) throw Object.assign(new Error('Product import batch not found.'), { status: 404 });

  const item = (batch.items || []).find((row) => row.itemId === itemId);
  if (!item) throw Object.assign(new Error('Batch item not found.'), { status: 404 });

  const draft = item.draft || {};
  const cataloguePresets = batch.catalogue?.presets || {};
  const snapshot = await getSnapshot(shopDomain);
  const similar = similarExamples(draft, snapshot.seoExamples || []);
  const products = similar.map((row) => row.product);
  const recommendations = [];

  const vendorMode = mode(products.map((row) => row.vendor));
  const typeMode = mode(products.map((row) => row.productType));
  const templateMode = mode((snapshot.templates || []).filter((row) => row.template && row.template !== 'default').map((row) => row.template));
  const suffix = seoSuffix(similar);

  if (vendorMode && keyText(vendorMode) !== keyText(draft.vendor || '')) {
    pushRecommendation(recommendations, {
      field: 'vendor',
      label: 'Vendor',
      value: vendorMode,
      source: 'shop_recommendation',
      confidence: Math.min(0.96, 0.62 + products.filter((row) => keyText(row.vendor) === keyText(vendorMode)).length * 0.05),
      reason: `${products.filter((row) => keyText(row.vendor) === keyText(vendorMode)).length} similar Shopify product(s) use this vendor.`,
    });
  }

  if (typeMode && keyText(typeMode) !== keyText(draft.productType || '')) {
    pushRecommendation(recommendations, {
      field: 'productType',
      label: 'Product type',
      value: typeMode,
      source: 'shop_recommendation',
      confidence: Math.min(0.95, 0.58 + products.filter((row) => keyText(row.productType) === keyText(typeMode)).length * 0.06),
      reason: `${products.filter((row) => keyText(row.productType) === keyText(typeMode)).length} similar Shopify product(s) use this product type.`,
    });
  }

  if (templateMode && !draft.themeTemplate) {
    pushRecommendation(recommendations, {
      field: 'themeTemplate',
      label: 'Theme template',
      value: templateMode,
      source: 'shop_recommendation',
      confidence: 0.62,
      reason: 'This is the most common non-default product template currently used by the shop.',
    });
  }

  if (suffix && draft.title) {
    const proposed = cleanText(`${draft.title} | ${suffix}`, 120);
    if (proposed && proposed !== cleanText(draft.seo?.title || '', 120)) {
      pushRecommendation(recommendations, {
        field: 'seo.title',
        label: 'SEO title',
        value: proposed,
        source: 'shop_recommendation',
        confidence: 0.72,
        reason: `Uses the recurring SEO-title ending found across similar Shopify products: "${suffix}".`,
      });
    }
  }

  let ai = null;
  if (useAi === true && products.length) {
    ai = await aiCopyRecommendations({ draft, examples: similar });

    if (ai && !ai.error) {
      [
        ['title', 'Title', ai.title],
        ['descriptionHtml', 'Description', ai.descriptionHtml],
        ['seo.title', 'SEO title', ai.seoTitle],
        ['seo.description', 'SEO description', ai.seoDescription],
      ].forEach(([field, label, value]) => {
        if (!value) return;
        const existingIndex = recommendations.findIndex((row) => row.field === field);
        const row = {
          field,
          label,
          value: cleanText(value, field === 'descriptionHtml' ? 12000 : 1000),
          source: 'ai_suggestion',
          confidence: 0.84,
          reason: `AI-refined using the current supplier facts plus the style of ${products.length} similar Shopify product(s). Nothing is applied automatically.`,
        };
        if (existingIndex >= 0) recommendations[existingIndex] = row;
        else recommendations.push(row);
      });
    }
  }

  return {
    itemId,
    provenance: buildProvenance(draft, cataloguePresets),
    recommendations,
    similarProductCount: products.length,
    examples: products.slice(0, 6).map((row) => ({
      title: row.title || '',
      handle: row.handle || '',
      vendor: row.vendor || '',
      productType: row.productType || '',
      seoTitle: row.seoTitle || '',
      seoDescription: row.seoDescription || '',
    })),
    ai: {
      requested: useAi === true,
      available: Boolean(process.env.OPENAI_API_KEY),
      error: ai?.error || '',
    },
  };
}

module.exports = { buildProductFieldRecommendations, buildProvenance, similarExamples };
